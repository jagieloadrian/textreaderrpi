void display_init(void) {
    Wire.begin();
    s_matrix.begin(0x70);
    s_matrix.setBrightness(15);
    s_matrix.clear();
    s_matrix.writeDisplay();
}

void display_clear(void) {
    s_matrix.clear();
    s_matrix.writeDisplay();
}

void display_text(const char *text, const char *effect, int speed_ms) {
    int sp = clamp_speed(speed_ms);
    if (strcmp(effect, "SCROLL") == 0) {
        for (int i = 0; text[i]; i++) { render_char(text[i]); delay(sp); }
    } else if (strcmp(effect, "BLINK") == 0) {
        render_char(text[0]);
        int hw_blink = (sp >= 1000) ? 3 : (sp >= 500) ? 2 : 1;
        s_matrix.blinkRate(hw_blink);
        delay(sp * 6);
        s_matrix.blinkRate(0);
    } else if (strcmp(effect, "REVERSE") == 0) {
        int len = strlen(text);
        for (int i = len - 1; i >= 0; i--) { render_char(text[i]); delay(sp); }
    } else if (strcmp(effect, "FADE") == 0) {
        render_char(text[0]);
        int sd = sp / 16 + 1;
        for (int v = 0; v <= 15; v++) { s_matrix.setBrightness(v); delay(sd); }
        for (int v = 15; v >= 0; v--) { s_matrix.setBrightness(v); delay(sd); }
        s_matrix.setBrightness(15);
    }
}

